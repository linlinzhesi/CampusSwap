# ============================================================
# app/database.py
# 作用：负责「连接数据库」和「管理数据库会话」
# 这是整个项目的数据库基础，所有增删改查都靠它
# ============================================================

# 从 SQLAlchemy 导入所需组件
from sqlalchemy import create_engine          # 创建数据库引擎（负责真正连数据库）
from sqlalchemy.orm import sessionmaker       # 创建「会话工厂」（会话=一次数据库操作连接）
from sqlalchemy.orm import declarative_base   # 声明式基类（所有模型类都继承它）

# 导入配置
from .config import DATABASE_URL

# ------------------------------------------------------------------
# 第一步：创建数据库引擎（engine）
# create_engine 会根据上面的 URL 建立和 MySQL 的连接
# pool_pre_ping=True：每次用连接前先「探活」，如果连接断了会自动重连
#                     （避免长时间不用后连接失效报错）
# ------------------------------------------------------------------
engine = create_engine(DATABASE_URL, pool_pre_ping=True)

# ------------------------------------------------------------------
# 第二步：创建会话工厂（SessionLocal）
# 每次要操作数据库时，就 new 一个 Session 出来，用完关掉
# autocommit=False：不自动提交，需要手动 commit（保证事务可控）
# autoflush=False：不自动刷新（避免一些边界问题）
# ------------------------------------------------------------------
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

# ------------------------------------------------------------------
# 第三步：创建基类（Base）
# 所有「数据库表对应的 Python 类」（模型）都要继承这个 Base
# 这样 SQLAlchemy 才知道「哪些类是需要映射成表的」
# ------------------------------------------------------------------
Base = declarative_base()


# ------------------------------------------------------------------
# 依赖函数：get_db
# 作用：FastAPI 里用来「获取一个数据库会话」的标准写法
#       用 yield 的原因：请求开始时创建会话，请求结束时自动关闭，
#       确保不会忘记关连接、不会泄漏连接池
# ------------------------------------------------------------------
def get_db():
    db = SessionLocal()      # 创建一次会话
    try:
        yield db             # 把会话交给接口函数使用
    finally:
        db.close()           # 无论成功失败，最后一定关闭会话
